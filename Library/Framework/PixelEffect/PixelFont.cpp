	char ToUpperAscii( char Ch )
	{
		if ( Ch >= 'a' && Ch <= 'z' )
		{
			return static_cast<char>( Ch - 'a' + 'A' );
		}
		return Ch;
	}

	const char* FindGlyphPattern( EPixelFont Font, char Ch )
	{
		const FGlyphEntry* Table = ( Font == EPixelFont::Big ) ? BigGlyphs : MiniGlyphs;
		const int32 Count = ( Font == EPixelFont::Big )
			? static_cast<int32>( sizeof( BigGlyphs ) / sizeof( BigGlyphs[0] ) )
			: static_cast<int32>( sizeof( MiniGlyphs ) / sizeof( MiniGlyphs[0] ) );
		for ( int32 Index = 0; Index < Count; ++Index )
		{
			if ( Table[Index].Character == Ch )
			{
				return Table[Index].Pattern;
			}
		}
		const char Upper = ToUpperAscii( Ch );
		if ( Upper != Ch )
		{
			for ( int32 Index = 0; Index < Count; ++Index )
			{
				if ( Table[Index].Character == Upper )
				{
					return Table[Index].Pattern;
				}
			}
		}
		return nullptr;
	}

	int32 GetPatternWidth( const char* Pattern )
	{
		if ( Pattern == nullptr )
		{
			return 0;
		}
		int32 Width = 0;
		while ( Pattern[Width] != '\0' && Pattern[Width] != '|' )
		{
			++Width;
		}
		return Width;
	}
