#pragma once
#include <cstdint>
#include <cstddef>

#include "Library/Core/Types/CompilerMacros.h"

//=============================================================================
// 符号あり整数
//=============================================================================
using int8  = std::int8_t;   //  8bit  [-128, 127]
using int16 = std::int16_t;  // 16bit  [-32768, 32767]
using int32 = std::int32_t;  // 32bit  [-2147483648, 2147483647]
using int64 = std::int64_t;  // 64bit

//=============================================================================
// 符号なし整数
//=============================================================================
using uint8  = std::uint8_t;   //  8bit  [0, 255]
using uint16 = std::uint16_t;  // 16bit  [0, 65535]
using uint32 = std::uint32_t;  // 32bit  [0, 4294967295]
using uint64 = std::uint64_t;  // 64bit

//=============================================================================
// 浮動小数点
//=============================================================================
using float32 = float;   // 32bit 単精度
using float64 = double;  // 64bit 倍精度

//=============================================================================
// サイズ / ポインタ関連
//=============================================================================
using usize   = std::size_t;     // オブジェクトのバイトサイズ・配列インデックス用
using isize   = std::ptrdiff_t;  // ポインタ間の差分（符号あり）
using uintptr = std::uintptr_t;  // ポインタを格納できる符号なし整数
using intptr  = std::intptr_t;   // ポインタを格納できる符号あり整数
using byte    = std::uint8_t;    // 生バイト操作用

